#!/usr/bin/env python3
"""Developer tool: builds knownfiles.h - the list of GOG EU2 files eu2conv converts,
identified by SHA-1 and size (facts about the files, no file contents).

  python3 gen_knownfiles.py innodump.txt files.sha1 > knownfiles.h

innodump.txt : output of build/host/innodump on setup_europa_universalis2_2.0.0.1.exe
files.sha1   : "sha1<TAB>path" for every file innoextract wrote (paths start with app/ or tmp/)
"""
import sys

SKIP_EXT = {'exe', 'dll', 'tlb', 'scc', 'pdf', 'doc', 'ico', 'hashdb', 'info', 'zip', 'bat'}

def main():
    dump, sums = sys.argv[1], sys.argv[2]
    entries = {}                       # sha1 -> size (from the installer itself)
    for line in open(dump):
        f = line.split()
        if len(f) == 12 and f[1] == 'chunk':
            entries[f[11]] = int(f[8])
    rows = []
    for line in open(sums, encoding='utf-8'):
        sha, path = line.rstrip('\n').split('\t', 1)
        if not path.startswith('app/'):
            continue
        rel = path[4:]
        name = rel.rsplit('/', 1)[-1]
        ext = name.rsplit('.', 1)[-1].lower() if '.' in name else ''
        if ext in SKIP_EXT:
            continue
        if sha not in entries:
            sys.exit('no installer entry for ' + path)
        rows.append((rel.lower(), rel, sha, entries[sha]))
    rows.sort()
    out = sys.stdout
    out.write('/* knownfiles.h - GENERATED by gen_knownfiles.py, do not edit.\n')
    out.write(' * GOG Europa Universalis II v1.09 (setup_europa_universalis2_2.0.0.1.exe):\n')
    out.write(' * the files eu2conv uses, identified by SHA-1 and size. */\n')
    out.write('typedef struct { const char *path; unsigned long size; const char *sha1; } KnownFile;\n')
    out.write('static const KnownFile known_files[] = {\n')
    for _, rel, sha, size in rows:
        p = rel.replace('\\', '\\\\').replace('"', '\\"')
        out.write('\t{ "%s", %dUL, "%s" },\n' % (p, size, sha))
    out.write('};\n#define KNOWN_FILES_COUNT %d\n' % len(rows))

if __name__ == '__main__':
    main()
